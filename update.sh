#!/bin/bash

set -e

echo "================================================================================"
echo "1. Current status"
echo "================================================================================"
git status
echo "================================================================================"
echo

git add -u
# Add new files
for f in $(git status | grep -E '.*\.py|.*\.sh|.*\.md|.*\.png|.*\.jpeg' | grep -v 'modified' | grep -v 'new file')
do
  git add $f
done

echo "================================================================================"
echo "2. Next status"
echo "================================================================================"
git status
today=$(date "+%Y%m%d")
git commit -m "Update on ${today}"

git push
echo "================================================================================"
echo

echo "================================================================================"
echo "3. Final status"
echo "================================================================================"
git status
echo "================================================================================"
echo
