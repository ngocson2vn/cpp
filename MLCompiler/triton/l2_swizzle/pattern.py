GROUP_M = 8
grid_m = 16 
grid_n = 4
# => total programs = grid_m * grid_n = 64
# pid = 0, 1, 2, ..., 63

#     --- start group 0 --->|------|------|------|------|
#                           |  0,0 |  0,1 |  0,2 |  0,3 |
#                           |------|------|------|------|
#                           |  1,0 |  1,1 |  1,2 |  1,3 |
#                           |------|------|------|------|
#                           |  2,0 |  2,1 |  2,2 |  2,3 |
#                           |------|------|------|------|
#                           |  3,0 |  3,1 |  3,2 |  3,3 |
#                           |------|------|------|------|
#                           |  4,0 |  4,1 |  4,2 |  4,3 |
#                           |------|------|------|------|
#                           |  5,0 |  5,1 |  5,2 |  5,3 |
#                           |------|------|------|------|
#                           |  6,0 |  6,1 |  6,2 |  6,3 |
#                           |------|------|------|------|
#                           |  7,0 |  7,1 |  7,2 |  7,3 |
#     --- start group 1 --->|------|------|------|------|<--- end group 0 ---
#                           |  8,0 |  8,1 |  8,2 |  8,3 |
#                           |------|------|------|------|
#                           |  9,0 |  9,1 |  9,2 |  9,3 |
#                           |------|------|------|------|
#                           | 10,0 | 10,1 | 10,2 | 10,3 |
#                           |------|------|------|------|
#                           | 11,0 | 11,1 | 11,2 | 11,3 |
#                           |------|------|------|------|
#                           | 12,0 | 12,1 | 12,2 | 12,3 |
#                           |------|------|------|------|
#                           | 13,0 | 13,1 | 13,2 | 13,3 |
#                           |------|------|------|------|
#                           | 14,0 | 14,1 | 14,2 | 14,3 |
#                           |------|------|------|------|
#                           | 15,0 | 15,1 | 15,2 | 15,3 |
#                           |------|------|------|------|<--- end group 1 ---


for pid in range(grid_m * grid_n):
    # The number of pids in a group
    group_size = GROUP_M * grid_n

    # group_id equals
    #   0 for  0 <= pid <= 31
    #   1 for 32 <= pid <= 63 
    group_id = pid // group_size

    # group_height always equals 8
    group_height = min(grid_m - group_id * GROUP_M, GROUP_M)

    pid_m = group_id * GROUP_M + (pid % group_height)
    pid_n = (pid % group_size) // group_height
    print("pid={0:>2}:".format(str(pid)), "{0:>2}".format(str(pid_m)), pid_n)
